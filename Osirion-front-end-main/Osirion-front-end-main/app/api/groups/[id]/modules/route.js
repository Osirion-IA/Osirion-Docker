import { NextResponse } from "next/server";

// Bascule en masse des modules d'un groupe (facial / LPR)
// → backend PATCH /groups/{id}/modules  body: {is_facial_active?, is_lpr_active?}
export async function PATCH(req, { params }) {
  try {
    const backendUrl = process.env.NEXT_PUBLIC_BASE_BACKEND_URL;
    const accessToken = req.cookies.get("access_token")?.value;
    if (!accessToken) {
      return NextResponse.json({ message: "Non authentifié." }, { status: 401 });
    }

    const { id } = params;
    const body = await req.json();
    const response = await fetch(`${backendUrl}/groups/${id}/modules`, {
      method: "PATCH",
      headers: {
        "Authorization": `Bearer ${accessToken}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify(body),
    });

    const data = await response.json();
    if (!response.ok) {
      return NextResponse.json({ message: data?.detail || "Erreur lors de la bascule des modules." }, { status: response.status });
    }
    return NextResponse.json(data);
  } catch (err) {
    return NextResponse.json({ message: "Erreur serveur." }, { status: 500 });
  }
}
